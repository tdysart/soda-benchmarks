#!/usr/bin/env python3
"""Write the testbench C file bambu runs (--generate-tb) from a testdata.h.

    scripts/gen_bambu_tb.py <testdata.h> <out.c>

It has the shape of the one soda-opt writes during lowering (one array per argument, m_param_alloc,
the call), but with the kernel's real inputs (PolyBench's init_array through torchscript.py
--emit-testdata, or a TensorFlow model's own through scripts/tf_testdata.py) instead of soda-opt's constant ones, and the result buffers starting at zero.
soda-opt's inputs are all 1.0, which hides whole classes of errors (swapped arguments, a transposed
access). The memory bambu records after running it natively is the reference the Verilog is checked
against, and scripts/check_golden.py compares it with the framework's result.
"""
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from testdata import TestData

PRELUDE = """#define _FILE_OFFSET_BITS 64
#ifdef __cplusplus
#undef printf
#include <cstdio>
#include <cstdlib>
#else
#include <stdio.h>
#include <stdlib.h>
#endif
#include <sys/types.h>
#ifndef CDECL
#ifdef __cplusplus
#define CDECL extern "C"
#else
#define CDECL
#endif
#endif
#include <mdpi/mdpi_user.h>
"""


def main():
    td = TestData(sys.argv[1])
    args = td.call_arrays()
    parts = [f"/* generated by scripts/gen_bambu_tb.py from {sys.argv[1].rsplit('/', 1)[-1]}: do not edit */", PRELUDE]
    parts.append("CDECL void forward_kernel(" + ", ".join(["void*"] * len(args)) + ");\n")
    parts.append("int main()\n{")
    for j in range(len(args)):
        parts.append(f"   void* P{j};")
    for j, vals in enumerate(args):
        body = ",".join(repr(v) for v in vals)
        parts.append(f"   {{\n      {td.ctype} P{j}_temp[] = {{{body}}};\n      P{j} = (void*)P{j}_temp;\n"
                     f"      m_param_alloc({j}, sizeof(P{j}_temp));")
    # the arrays must live until the call, so the call goes inside the last block
    parts.append("      forward_kernel(" + ", ".join(f"(void*) P{j}" for j in range(len(args))) + ");")
    parts.append("   " + "}" * len(args))
    parts.append("   return 0;\n}")
    open(sys.argv[2], "w").write("\n".join(parts).replace("   }\n      forward_kernel", "      forward_kernel") + "\n")
    print(f"{sys.argv[2]}: {len(args)} arguments, results are arguments {td.out_positions()}")


if __name__ == "__main__":
    main()
