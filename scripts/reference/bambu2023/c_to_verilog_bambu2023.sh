#!/bin/bash
# Synthesize a C kernel with bambu v2023.1 and generate its self-contained,
# pure-Verilog testbench from an XML test vector.
#
# Usage: c_to_verilog_bambu2023.sh <input.c> <test.xml> <output.v>
#
# bambu v2023.1 is used for its --generate-tb=<file.xml> testbench, which has
# no DPI-C dependency (newer bambu replaced it with a DPI-C testbench), so the
# generated simulation model can run under verilator-sst as is. Its only front
# end is I386_CLANG13, which cannot read LLVM 19 IR, so the input is C
# (see ll_to_c_cbe.sh).
#
# Runs locally only (no docker). Outputs land next to <output.v>: bambu's
# forward_kernel.v copied to 06_verilog.v, the testbench under
# HLS_output/simulation/, and, when simulating, 07_results.txt. The testbench
# has the absolute paths of values.txt and results.txt baked in.
#
# Environment:
#   BAMBU2023             bambu v2023.1 binary (default: bambu on PATH)
#   BAMBU_DEVICE          (default: asap7-BC)
#   BAMBU_CLOCK_PERIOD    (default: 5)
#   BAMBU_MEMPOLICY       (default: NO_BRAM)
#   BAMBU_RUN_SIMULATION  true to also simulate with Verilator (default: false)

set -e -o pipefail

SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" &> /dev/null && pwd )"

if [ "$#" -ne 3 ]; then
  echo "Usage: $0 <input.c> <test.xml> <output.v>" >&2
  exit 1
fi

BAMBU2023="${BAMBU2023:-bambu}"
BAMBU_DEVICE="${BAMBU_DEVICE:-asap7-BC}"
BAMBU_MEMPOLICY="${BAMBU_MEMPOLICY:-NO_BRAM}"
BAMBU_CLOCK_PERIOD="${BAMBU_CLOCK_PERIOD:-5}"
BAMBU_RUN_SIMULATION="${BAMBU_RUN_SIMULATION:-false}"

if ! command -v "$BAMBU2023" &> /dev/null; then
  echo "ERROR: $BAMBU2023 could not be found. Set BAMBU2023 to the v2023.1 bambu binary." >&2
  exit 1
fi
if ! "$BAMBU2023" --version 2>&1 | grep -q "PandA 2023\."; then
  echo "ERROR: $BAMBU2023 is not bambu v2023.x:" >&2
  "$BAMBU2023" --version 2>&1 | grep "Version:" >&2
  exit 1
fi

# Homebrew's clang does not find the macOS SDK on its own; bambu compiles and
# links the host-side testbench (values.c) with it.
if [ "$(uname)" = "Darwin" ]; then
  export SDKROOT="${SDKROOT:-$(xcrun --show-sdk-path)}"
  EXTRA_TB_FLAGS="--testbench-extra-gcc-flags=-L${SDKROOT}/usr/lib"
fi

TEST_XML="$(cd "$(dirname "$2")" && pwd)/$(basename "$2")"
OUTPUT_DIR=$(pwd)/$(dirname $3)
mkdir -p $OUTPUT_DIR

cp $1 $OUTPUT_DIR/input.c
pushd $OUTPUT_DIR

SIMULATION_ARGS=""
if [ "$BAMBU_RUN_SIMULATION" = "true" ]; then
  SIMULATION_ARGS="--simulate --simulator=VERILATOR --verilator-parallel"
fi

"$BAMBU2023" -v3 --print-dot \
	-lm --soft-float \
	--compiler=I386_CLANG13 \
	--device=$BAMBU_DEVICE \
	--clock-period=$BAMBU_CLOCK_PERIOD \
	--experimental-setup=BAMBU-BALANCED-MP \
	--channels-number=2 \
	--memory-allocation-policy=$BAMBU_MEMPOLICY \
	--disable-function-proxy \
	--extra-gcc-options=-ffp-contract=off \
	$EXTRA_TB_FLAGS \
	--generate-tb=$TEST_XML \
	$SIMULATION_ARGS \
	--top-fname=forward_kernel \
	input.c 2>&1 | tee bambu-log

cp forward_kernel.v 06_verilog.v

# If simulation was requested, copy results from results.txt to 07_results.txt
if [ "$BAMBU_RUN_SIMULATION" = "true" ]; then
  if [ -f results.txt ]; then
    cp results.txt 07_results.txt
  else
    echo "No results.txt found, skipping copying results."
  fi
fi

# Patch OpenROAD scripts generated by bambu only for specific devices
case "$BAMBU_DEVICE" in
  asap7-BC|asap7-TC|asap7-WC|nangate45)
    BAMBUDIR=$OUTPUT_DIR
    KERNELNAME=forward_kernel
    # If asap7-BC, this removes -BC from the device name leaving just asap7
    PLATFORM=${BAMBU_DEVICE%-*}
    source ${SCRIPT_DIR}/../../patch_openroad_synt.sh
    ;;
esac

popd
