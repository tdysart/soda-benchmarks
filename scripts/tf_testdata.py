#!/usr/bin/env python3
"""Write a TensorFlow model's testdata.h: its inputs and the results TensorFlow computes from them.

    scripts/tf_testdata.py <frozen_graph.pbtxt> <model_script.py> <out.h>
        --kernel NAME --inputs x1 --outputs Identity [--arg-order "0 1"]

The counterpart of torchscript.py --emit-testdata for a TensorFlow model, in the same format
(scripts/testdata.py reads it), so the rest of the flow is the PyTorch kernels' own: bambu's testbench
on these inputs (scripts/gen_bambu_tb.py), and the check of bambu's native run against these results
with model.json (scripts/write_model_json.py).

The reference is the frozen graph itself, the graph tf-mlir-translate turned into the kernel, run
with the same input and output arrays as that translation (--inputs, --outputs), so it is the same
computation with the same weights. The model script gives the inputs, as PolyBench's init_array does
for the PyTorch kernels:

    init_inputs()    a list of numpy arrays, one per --inputs entry, in that order
    DATASET          a name for those inputs (optional; "default")
    RESULT_NAMES     a name per --outputs entry (optional; the array names)

--arg-order is the order the outlined forward_kernel takes @forward's parameters in (the inputs,
then one buffer per result), as scripts/kernel_arg_order.sh prints it; the identity by default.
Needs a Python with TensorFlow.
"""
import argparse
import importlib.util
import os

import numpy as np
import tensorflow as tf
from google.protobuf import text_format

C_TYPES = {"float32": "float", "float64": "double"}
TOLERANCE = {"float32": "1e-3", "float64": "1e-9"}


def c_array(values, per_line=8):
    items = [f"{float(v)!r}" for v in values]
    return "\n".join("    " + ", ".join(items[i:i + per_line]) + "," for i in range(0, len(items), per_line))


def shape(a):
    return "x".join(str(d) for d in a.shape) or "scalar"


def run_graph(path, inputs, outputs, values):
    graph_def = tf.compat.v1.GraphDef()
    with open(path) as f:
        text_format.Parse(f.read(), graph_def)
    graph = tf.Graph()
    with graph.as_default():
        tf.import_graph_def(graph_def, name="")
    with tf.compat.v1.Session(graph=graph) as sess:
        return sess.run([f"{o}:0" for o in outputs], {f"{i}:0": v for i, v in zip(inputs, values)})


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("graph")
    ap.add_argument("script")
    ap.add_argument("out")
    ap.add_argument("--kernel", required=True)
    ap.add_argument("--inputs", required=True, help="the graph's input arrays, comma-separated")
    ap.add_argument("--outputs", required=True, help="the graph's output arrays, comma-separated")
    ap.add_argument("--arg-order", default=None)
    args = ap.parse_args()
    in_arrays, out_arrays = args.inputs.split(","), args.outputs.split(",")

    spec = importlib.util.spec_from_file_location("model_script", args.script)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    inputs = [np.asarray(x) for x in mod.init_inputs()]
    if len(inputs) != len(in_arrays):
        raise SystemExit(f"tf_testdata.py: init_inputs() gave {len(inputs)} arrays for {len(in_arrays)} inputs")
    dtype = inputs[0].dtype.name
    if dtype not in C_TYPES or any(x.dtype.name != dtype for x in inputs):
        raise SystemExit(f"tf_testdata.py: the inputs must all be one of {sorted(C_TYPES)}")
    dataset = getattr(mod, "DATASET", "default")
    result_names = list(getattr(mod, "RESULT_NAMES", out_arrays))

    goldens = [np.asarray(g, dtype=dtype) for g in run_graph(args.graph, in_arrays, out_arrays, inputs)]
    n_in, n_out = len(inputs), len(goldens)
    order = [int(t) for t in args.arg_order.replace(",", " ").split()] if args.arg_order else list(range(n_in + n_out))
    if sorted(order) != list(range(n_in + n_out)):
        raise SystemExit(f"tf_testdata.py: --arg-order must be a permutation of 0..{n_in + n_out - 1}, got {order}")

    k = args.kernel
    parts = [
        "/* testdata.h — generated by scripts/tf_testdata.py.",
        " *",
        f" * Kernel: {k}   Dataset: {dataset}   Dtype: {dtype}   Framework: TensorFlow",
        " * Consumed by scripts/lib/soda_testbench_main.c.",
        " */",
        "#ifndef SODA_TESTDATA_H",
        "#define SODA_TESTDATA_H",
        "",
        f'#define TD_KERNEL  "{k}"',
        f'#define TD_DATASET "{dataset}"',
        f'#define TD_DTYPE   "{dtype}"',
        f"#define TD_TOL     {TOLERANCE[dtype]}",
        '#define TD_FRAMEWORK "tensorflow"',
        "",
        f"typedef {C_TYPES[dtype]} td_elem_t;",
        "",
    ]
    names = []
    for i, x in enumerate(inputs):
        names.append(f"td_p{i}")
        parts += [f"/* parameter {i}: shape {shape(x)} */", f"static td_elem_t td_p{i}[{x.size}] = {{",
                  c_array(x.reshape(-1)), "};", ""]
    out_names, golden_names, count_names = [], [], []
    for j, g in enumerate(goldens):
        sfx = "" if n_out == 1 else str(j)
        out_names.append(f"td_out{sfx}")
        golden_names.append(f"td_golden{sfx}")
        count_names.append(f"TD_OUT_N{sfx}")
        parts += [f"/* result{'' if n_out == 1 else ' ' + str(j)}: shape {shape(g)} */",
                  f"static td_elem_t {out_names[-1]}[{g.size}];", "",
                  f"static const td_elem_t {golden_names[-1]}[{g.size}] = {{", c_array(g.reshape(-1)), "};", ""]
    if n_out == 1:
        parts.append("#define TD_OUT     td_out")
    parts += [f"#define {count_names[j]} {goldens[j].size}" for j in range(n_out)]
    parts += [f"#define TD_NOUT    {n_out}",
              "/* TD_OUTPUTS(X): X(buffer, golden, count) for each result, in order */",
              "#define TD_OUTPUTS(X) " + " ".join(f"X({out_names[j]}, {golden_names[j]}, {count_names[j]})"
                                                  for j in range(n_out)),
              ""]
    call = names + out_names
    parts += ["/* forward_kernel's parameter order, which -soda-outline-bambu-code",
              f" * derived by first use: {order} into @forward's signature. */",
              "#define TD_CALL(F) F(" + ", ".join(call[i] for i in order) + ")",
              "#define TD_DECL(F) void F(" + ", ".join(["td_elem_t *"] * len(order)) + ")",
              "",
              "/* @forward's parameter names, in @forward's order, and its results' names */",
              f'#define TD_PARAM_NAMES "{" ".join(in_arrays)}"',
              f'#define TD_RESULT_NAMES "{" ".join(result_names)}"',
              "",
              "#endif /* SODA_TESTDATA_H */",
              ""]
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))
    print(f"Test data written to {args.out}: {k}, {n_in} input(s), {n_out} result(s), dataset {dataset}")


if __name__ == "__main__":
    main()
